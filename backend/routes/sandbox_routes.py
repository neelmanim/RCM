# ── Refresh (Mirror Mode) ───────────────────────────────────────────────────

def _do_refresh(prod_url: str, token: str):
    """Background worker: pull anonymized data from prod table-by-table and write to staging DB."""
    global _refresh_progress
    from database import SessionLocal
    import httpx

    _refresh_progress.update(status="running", step="Connecting to production API...",
                             percent=5, error=None, started_at=datetime.now(timezone.utc).isoformat())
    db = SessionLocal()
    hdr = {"X-Sandbox-Token": token}

    def _prod_get(path: str, timeout: int = 30):
        """GET from prod with consistent error handling."""
        resp = httpx.get(f"{prod_url}{path}", headers=hdr, timeout=timeout)
        if resp.status_code == 401:
            raise Exception("Sandbox token was revoked or regenerated on production. Please get the new token.")
        if resp.status_code != 200:
            raise Exception(f"Production returned HTTP {resp.status_code} for {path}")
        try:
            return resp.json()
        except Exception:
            raise Exception(f"Production returned non-JSON response for {path} (body: {resp.text[:200]!r})")

    try:
        # Step 1: Get table list + counts
        _refresh_progress.update(step="Fetching table list from production...", percent=10)
        tables_data = _prod_get("/api/admin/sandbox/export/tables")
        tables = tables_data.get("tables", {})
        total_records = tables_data.get("total_records", 0)

        # Exclude tables staging manages itself
        inspector = sa_inspect(engine)
        staging_tables = set(inspector.get_table_names())
        tables_to_write = [
            t for t in tables.keys()
            if t in staging_tables and t not in SKIP_TABLES and t != "sync_settings"
        ]

        _refresh_progress.update(
            step=f"Found {total_records} records across {len(tables_to_write)} tables. Starting import...",
            percent=15, detail=f"{total_records} total records"
        )

        from sqlalchemy import text
        lead_count = 0
        progress_per_table = 80 / max(len(tables_to_write), 1)
        current_progress = 15

        # Step 2: Per-table export + write
        for i, table_name in enumerate(tables_to_write):
            row_count = tables.get(table_name, 0)
            _refresh_progress.update(
                step=f"[{i+1}/{len(tables_to_write)}] Pulling {table_name} ({row_count} rows)...",
                percent=int(current_progress),
            )

            # Fetch this table from prod
            try:
                tdata = _prod_get(f"/api/admin/sandbox/export/table/{table_name}", timeout=30)
                rows = tdata.get("rows", [])
            except Exception as e:
                logger.warning(f"Sandbox refresh: skipped {table_name}: {e}")
                current_progress += progress_per_table
                continue

            # Write to staging — each table is its own transaction boundary
            try:
                db.execute(text(f'TRUNCATE TABLE "{table_name}" CASCADE'))
                if rows:
                    table_obj = models.Base.metadata.tables.get(table_name)
                    if table_obj is not None:
                        staging_cols = {c.name for c in table_obj.columns}
                        clean_rows = [{k: v for k, v in r.items() if k in staging_cols} for r in rows]
                        if clean_rows:
                            db.execute(table_obj.insert(), clean_rows)
                db.commit()  # Commit each table independently
                if table_name == "leads":
                    lead_count = len(rows)
            except Exception as e:
                db.rollback()  # Rollback so next table starts with a clean transaction
                logger.warning(f"Sandbox refresh: write failed for {table_name}: {e}")

            current_progress += progress_per_table

        # Commit
        db.commit()

        settings = _get_or_create_sync_settings(db)
        settings.sandbox_last_refresh_at = datetime.now(timezone.utc)
        settings.sandbox_last_refresh_status = "success"
        settings.sandbox_refresh_lead_count = lead_count
        db.commit()

        _refresh_progress.update(
            status="done", step="✅ Refresh complete!",
            percent=100, lead_count=lead_count,
            finished_at=datetime.now(timezone.utc).isoformat(),
        )
        logger.info(f"Sandbox refresh complete: {lead_count} leads, {len(tables_to_write)} tables")

    except Exception as e:
        db.rollback()
        error_msg = str(e)
        logger.error(f"Sandbox refresh failed: {error_msg}")
        try:
            settings = _get_or_create_sync_settings(db)
            settings.sandbox_last_refresh_status = "failed"
            db.commit()
        except Exception:
            pass
        _refresh_progress.update(
            status="failed", step="❌ Refresh failed",
            error=error_msg,
            finished_at=datetime.now(timezone.utc).isoformat(),
        )
    finally:
        db.close()
        _refresh_lock.release()


@router.post("/refresh")
def trigger_refresh(
    body: dict,
    db: Session = Depends(get_db),
    admin: dict = Depends(require_super_admin),
):
    """Trigger a mirror-mode refresh from production (staging only)."""
    _require_staging()

    # Verify confirmation
    if body.get("confirm") != "REFRESH":
        raise HTTPException(status_code=400, detail="Type REFRESH to confirm.")

    # Check connection
    settings = _get_or_create_sync_settings(db)
    if not settings.sandbox_prod_url or not settings.sandbox_prod_token:
        raise HTTPException(status_code=400, detail="Not connected to production. Set up the connection first.")

    # Concurrency guard
    if not _refresh_lock.acquire(blocking=False):
        raise HTTPException(status_code=423, detail="A refresh is already in progress.")

    try:
        prod_url = decrypt_token(settings.sandbox_prod_url)
        token = decrypt_token(settings.sandbox_prod_token)
    except Exception:
        _refresh_lock.release()
        raise HTTPException(status_code=500, detail="Failed to decrypt stored connection details.")

    # Reset progress
    global _refresh_progress
    _refresh_progress = {
        "status": "running", "step": "Starting...", "percent": 0,
        "detail": "", "started_at": datetime.now(timezone.utc).isoformat(),
        "finished_at": None, "lead_count": 0, "error": None,
    }

    # Run in background thread
    thread = threading.Thread(target=_do_refresh, args=(prod_url, token), daemon=True)
    thread.start()

    logger.info(f"Sandbox refresh triggered by {admin.get('email')}")
    return {"success": True, "message": "Refresh started. Poll /status for progress."}


