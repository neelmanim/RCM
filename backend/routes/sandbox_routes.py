# ── Clear Data ───────────────────────────────────────────────────────────────

@router.post("/clear")
def clear_staging_data(
    body: dict,
    db: Session = Depends(get_db),
    admin: dict = Depends(require_super_admin),
):
    """Clear all staging data except users and config (staging only)."""
    _require_staging()

    if body.get("confirm") != "CLEAR":
        raise HTTPException(status_code=400, detail="Type CLEAR to confirm.")

    from sqlalchemy import text

    # Tables to clear (order matters for FK constraints)
    clear_tables = [
        "lead_attachments", "lead_email_activity", "email_threads",
        "dialer_calls", "call_logs", "notes", "tasks",
        "lead_status_logs", "salesforce_integration_logs",
        "user_activity_logs", "user_activity_daily_summary",
        "login_logs", "feedback", "company_research",
    ]

    # Clear lead_assignments (association table)
    try:
        db.execute(text("DELETE FROM lead_assignments"))
    except Exception as e:
        logger.warning(f"Clear lead_assignments: {e}")

    # Clear dependent tables first, then leads
    cleared = []
    for table_name in clear_tables:
        try:
            db.execute(text(f'TRUNCATE TABLE "{table_name}" CASCADE'))
            cleared.append(table_name)
        except Exception as e:
            logger.warning(f"Clear {table_name}: {e}")

    # Clear leads last
    try:
        db.execute(text('TRUNCATE TABLE "leads" CASCADE'))
        cleared.append("leads")
    except Exception as e:
        logger.warning(f"Clear leads: {e}")

    db.commit()
    logger.info(f"Staging data cleared by {admin.get('email')}: {cleared}")
    return {"success": True, "message": f"Cleared {len(cleared)} tables.", "tables": cleared}


