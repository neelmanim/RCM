@router.post("/connection")
def save_connection(
    body: dict,
    db: Session = Depends(get_db),
    admin: dict = Depends(require_super_admin),
):
    """Save production URL + sandbox token (staging only)."""
    _require_staging()
    prod_url = (body.get("prod_url") or "").strip().rstrip("/")
    token = (body.get("token") or "").strip()

    if not prod_url or not token:
        raise HTTPException(status_code=400, detail="Production URL and sandbox token are required.")

    # Guard: prevent connecting to self
    my_url = os.getenv("RENDER_EXTERNAL_URL", "").strip().rstrip("/")
    allow_self = os.getenv("SANDBOX_ALLOW_SELF_TEST", "").lower() in ("true", "1")
    if my_url and prod_url.rstrip("/") == my_url and not allow_self:
        raise HTTPException(status_code=400, detail="This is the staging URL, not production.")

    # Test the connection by calling prod's token status — must return JSON
    import httpx
    try:
        resp = httpx.get(
            f"{prod_url}/api/admin/sandbox/export/count",
            headers={"X-Sandbox-Token": token},
            timeout=10,
        )
        if resp.status_code == 401:
            raise HTTPException(status_code=400, detail="Invalid token — production rejected it.")
        if resp.status_code != 200:
            raise HTTPException(status_code=400, detail=f"Production returned status {resp.status_code}")
        # Validate it's actually an API (not a frontend serving HTML)
        content_type = resp.headers.get("content-type", "")
        if "text/html" in content_type:
            raise HTTPException(
                status_code=400,
                detail=(
                    "The URL returned HTML instead of JSON — it points to a frontend, not the backend API. "
                    "Use the direct backend API URL (e.g. https://api.alternatecrm.com)."
                )
            )
        try:
            resp.json()
        except Exception:
            raise HTTPException(status_code=400, detail="Production did not return valid JSON. Check the URL.")
    except httpx.ConnectError:
        raise HTTPException(status_code=400, detail="Could not reach production. Check the URL.")
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Connection test failed: {str(e)}")

    # Store encrypted
    settings = _get_or_create_sync_settings(db)
    settings.sandbox_prod_url = encrypt_token(prod_url)
    settings.sandbox_prod_token = encrypt_token(token)
    db.commit()

    logger.info(f"Sandbox connection saved by {admin.get('email')}")
    return {"success": True, "message": "Connected to production."}


