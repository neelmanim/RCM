def _anonymize_leads(rows: list) -> list:
    """Anonymize lead records in-memory."""
    from faker import Faker
    fake = Faker()
    for r in rows:
        r["first_name"] = fake.first_name()
        r["last_name"] = fake.last_name()
        r["email"] = f"lead_{r.get('id', 'x')[:8]}@staging.test"
        r["phone"] = fake.phone_number() if r.get("phone") else None
        r["phone_secondary"] = None
        r["company"] = fake.company() if r.get("company") else None
        r["title"] = fake.job() if r.get("title") else None
        r["linkedin_url"] = None
        r["person_linkedin"] = None
        r["website"] = None
        r["company_phone"] = None
        r["company_linkedin"] = None
        r["company_street"] = None
        r["company_city"] = fake.city() if r.get("company_city") else None
        r["company_state"] = fake.state_abbr() if r.get("company_state") else None
        r["company_country"] = r.get("company_country")  # keep country
        r["company_postal_code"] = None
        # Scrub research fields
        for f in ["research_company", "research_contact", "research_hypothesis",
                   "research_personalization", "research_hook", "research_channels"]:
            if r.get(f):
                r[f] = _scrub_pii(r[f])
    return rows


def _anonymize_table(table_name: str, rows: list) -> list:
    """Apply table-specific anonymization rules."""
    if table_name == "leads":
        return _anonymize_leads(rows)

    from faker import Faker
    fake = Faker()

    for r in rows:
        if table_name == "notes":
            if r.get("content"):
                r["content"] = _scrub_pii(r["content"])

        elif table_name == "call_logs":
            if r.get("notes"):
                r["notes"] = _scrub_pii(r["notes"])

        elif table_name == "login_logs":
            r["email"] = f"user_{r.get('user_id', 'x')[:6]}@staging.test"
            r["ip_address"] = f"192.168.0.{hash(r.get('id', '')) % 255}"
            r["name"] = fake.name()
            r["user_agent"] = "Mozilla/5.0 (Staging)"

        elif table_name == "lead_email_activity":
            r["from_email"] = f"from_{r.get('id', 'x')[:6]}@staging.test"
            r["to_email"] = f"to_{r.get('id', 'x')[:6]}@staging.test"
            r["subject"] = "Staging email subject"
            if r.get("body_preview"):
                r["body_preview"] = _scrub_pii(r["body_preview"][:200])

        elif table_name == "salesforce_integration_logs":
            r["first_name"] = fake.first_name() if r.get("first_name") else None
            r["last_name"] = fake.last_name() if r.get("last_name") else None
            r["email"] = f"sf_{r.get('id', 'x')[:6]}@staging.test" if r.get("email") else None

        elif table_name in ("user_activity_logs", "user_activity_daily_summary"):
            r["user_email"] = f"user_{r.get('user_id', 'x')[:6]}@staging.test" if r.get("user_email") else None
            r["user_name"] = fake.name() if r.get("user_name") else None

        elif table_name == "feedback":
            r["user_email"] = f"fb_{r.get('id', 'x')[:6]}@staging.test" if r.get("user_email") else None
            r["message"] = _scrub_pii(r.get("message", ""))

        elif table_name == "dialer_calls":
            r["phone_number"] = fake.phone_number() if r.get("phone_number") else None
            if r.get("notes"):
                r["notes"] = _scrub_pii(r["notes"])
            if r.get("transcript"):
                r["transcript"] = _scrub_pii(r["transcript"])

        elif table_name == "email_threads":
            pass  # Only IDs and timestamps, no PII

        elif table_name == "lead_attachments":
            pass  # File metadata only, no PII in columns

    return rows


@router.get("/export/tables")
def export_table_list(
    request: Request,
    db: Session = Depends(get_db),
):
    """Return list of exportable tables + row counts. Token-authenticated."""
    _validate_sandbox_token(request, db)
    inspector = sa_inspect(engine)
    available_tables = inspector.get_table_names()
    tables = {}
    for table_name in available_tables:
        if table_name in SKIP_TABLES:
            continue
        try:
            table_obj = models.Base.metadata.tables.get(table_name)
            if table_obj is not None:
                count = db.execute(func.count().select_from(table_obj)).scalar()
                tables[table_name] = count
        except Exception:
            tables[table_name] = -1
    return {
        "success": True,
        "tables": tables,
        "total_records": sum(v for v in tables.values() if v > 0),
    }


@router.get("/export/table/{table_name}")
def export_single_table(
    table_name: str,
    request: Request,
    db: Session = Depends(get_db),
):
    """Export a single table, anonymized. Token-authenticated."""
    _validate_sandbox_token(request, db)
    if table_name in SKIP_TABLES:
        raise HTTPException(status_code=400, detail=f"Table '{table_name}' is not exportable.")

    table_obj = models.Base.metadata.tables.get(table_name)
    if table_obj is None:
        raise HTTPException(status_code=404, detail=f"Table '{table_name}' not found.")

    try:
        result = db.execute(table_obj.select())
        columns = result.keys()
        rows = [dict(zip(columns, row)) for row in result.fetchall()]
        for row in rows:
            for k, v in row.items():
                if isinstance(v, datetime):
                    row[k] = v.isoformat()
        if table_name not in COPY_AS_IS:
            rows = _anonymize_table(table_name, rows)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Export failed for table '{table_name}': {str(e)}")

    return {"success": True, "table": table_name, "row_count": len(rows), "rows": rows}


