#!/usr/bin/env node
// ============================================================================
// migrate-guide-sections.mjs — ONE-TIME migration tool, not shipped code.
// ============================================================================
// Extracts the 20 non-release-notes sections.push({...}) calls from
// frontend/js/views/user_guide.js and writes them to:
//   frontend-react/src/features/help-hub/data/sections.js
//
// Uses a real JS parser (acorn), not regex/brace-counting — several
// sections' `content` template literals contain nested ${...} expressions
// with their own template literals inside (e.g. line 96), which a naive
// brace/backtick counter cannot reliably delimit. Extracting each
// `content` value as an exact source-text slice (node.start..node.end)
// preserves it byte-for-byte, including the `${role...}` interpolations —
// those become real function parameters in the output, not hardcoded text.
//
// Usage: cd frontend-react && node scripts/migrate-guide-sections.mjs
// ============================================================================

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import * as acorn from 'acorn';

const ROOT = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const SOURCE = join(ROOT, 'frontend/js/views/user_guide.js');
const OUT = join(ROOT, 'frontend-react/src/features/help-hub/data/sections.js');

const code = readFileSync(SOURCE, 'utf8');
const ast = acorn.parse(code, { ecmaVersion: 2022, sourceType: 'module' });

// ── Walk the AST for every `sections.push({...})` call ─────────────────────
const pushCalls = [];
(function walk(node) {
  if (!node || typeof node.type !== 'string') return;
  if (
    node.type === 'CallExpression' &&
    node.callee.type === 'MemberExpression' &&
    node.callee.object.type === 'Identifier' && node.callee.object.name === 'sections' &&
    node.callee.property.type === 'Identifier' && node.callee.property.name === 'push'
  ) {
    pushCalls.push(node);
  }
  for (const key in node) {
    if (key === 'start' || key === 'end' || key === 'loc' || key === 'range') continue;
    const val = node[key];
    if (Array.isArray(val)) val.forEach(walk);
    else if (val && typeof val === 'object') walk(val);
  }
})(ast);

console.log(`Found ${pushCalls.length} sections.push({...}) calls.`);

const entries = [];
for (const call of pushCalls) {
  const objArg = call.arguments[0];
  if (!objArg || objArg.type !== 'ObjectExpression') throw new Error('sections.push() argument is not an object literal');

  const props = {};
  for (const prop of objArg.properties) {
    props[prop.key.name] = prop.value;
  }

  const titleNode = props.title;
  const rolesNode = props.roles;
  const contentNode = props.content;
  if (!titleNode || !rolesNode || !contentNode) throw new Error('Missing title/roles/content on a sections.push() entry');

  const title = code.slice(titleNode.start, titleNode.end); // keep as source (single-quoted string literal)
  const rolesSrc = code.slice(rolesNode.start, rolesNode.end); // e.g. ['sdr', 'pod_admin', 'super_admin']
  const contentSrc = code.slice(contentNode.start, contentNode.end); // the full `...` template literal, verbatim

  entries.push({ title, rolesSrc, contentSrc });
}

// The last entry is "What's New — Release Notes", already migrated to
// releases.json in a separate pass (migrate-release-notes.mjs) — exclude it.
const lastTitle = entries[entries.length - 1].title;
if (!lastTitle.includes("What")) {
  throw new Error(`Expected the last entry to be the What's New section, got: ${lastTitle}`);
}
const sectionEntries = entries.slice(0, -1);

if (sectionEntries.length !== 20) {
  throw new Error(`Expected exactly 20 non-release-notes sections, got ${sectionEntries.length}. Not writing output.`);
}

console.log(`Extracted ${sectionEntries.length} sections (excluding What's New, migrated separately):`);
for (const e of sectionEntries) console.log(`  - ${e.title}`);

// ── Write sections.js — content becomes a (role, roleName) => `...` function,
// preserving the exact original ${role}/${roleName} interpolation logic. ──
const body = sectionEntries.map((e, i) => `  {
    id: ${JSON.stringify(`section-${i}`)},
    title: ${e.title},
    roles: ${e.rolesSrc},
    content: (role, roleName) => ${e.contentSrc},
  }`).join(',\n');

const output = `// AUTO-GENERATED by scripts/migrate-guide-sections.mjs from
// frontend/js/views/user_guide.js — do not hand-edit; re-run the script if
// the classic source changes, or edit this file directly once the classic
// view is fully retired (see AGENT_PROTOCOL.md's help-hub cutover phase).
export const SECTIONS = [
${body}
];
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, output);
console.log(`\n✓ Wrote ${sectionEntries.length} sections to ${OUT}`);
